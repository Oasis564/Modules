def sum(num1, num2):
    return num1 + num2

def minus(num1, num2):
    return num1 - num2

def multiply(num1, num2):
    return num1 * num2

def division(num1, num2):
    return num1 / num2

def pow(num1, num2):
    return num1 ** num2

def arec(length, width):
    return length * width

def acirc(radius):
    return 3.14159 * radius ** 2

def atri(base, height):
    return 0.5 * base * height

def percentage(part, whole):
    return (part / whole) * 100